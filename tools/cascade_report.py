"""Generate The_400_Tasks/CASCADE_ANALYSIS.md from task_state.csv.

Identifies cascade-risk pools — external sources covering many tasks — and
ranks them by:
  - Pool size (how many tasks share the source)
  - Pool cost mass (sum of `current_cost` across the pool — bigger = more
    LB points at risk if the source cascades)
  - Headroom (sum of `gap_to_floor` across the pool — bigger = more room to
    cut by replacing the source with organics)
  - Solved overlap (how much of the pool is already in SOLVED_TASKS — low =
    big remaining opportunity)

Output sections:
  1. Top sources by task count (cascade risk magnitude)
  2. Top sources by cost mass (LB-points at risk)
  3. Top tasks within each source pool (ranked by current_cost, the
     individually-highest-ROI targets within that risk pool)
  4. Source ✕ family co-occurrence matrix (does a source cluster on one family?)

Usage:
    python tools/cascade_report.py [--csv PATH] [--out PATH]
"""
from __future__ import annotations

import argparse
import csv
import math
from collections import Counter, defaultdict
from pathlib import Path


REPO = Path(__file__).resolve().parents[1]
DEFAULT_CSV = REPO / "The_400_Tasks" / "task_state.csv"
DEFAULT_OUT = REPO / "The_400_Tasks" / "CASCADE_ANALYSIS.md"


def num(v, default: float = 0.0) -> float:
    if v is None or v == "":
        return default
    try:
        return float(v)
    except (TypeError, ValueError):
        return default


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--csv", type=Path, default=DEFAULT_CSV)
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    p.add_argument("--top-sources", type=int, default=12)
    p.add_argument("--top-tasks-per-source", type=int, default=10)
    args = p.parse_args(argv)

    with args.csv.open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))

    # Group rows by current_src
    by_src: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        src = (r.get("current_src") or "").strip()
        if not src:
            continue
        by_src[src].append(r)

    # Per-pool aggregates
    pools: list[dict] = []
    for src, members in by_src.items():
        cost_sum = sum(num(m.get("current_cost")) for m in members)
        gap_sum = sum(num(m.get("gap_to_floor")) for m in members)
        pts_sum = sum(num(m.get("current_points")) for m in members)
        n_solved = sum(1 for m in members if m.get("solved_status") == "Solved")
        n_hidden_bad = sum(1 for m in members if m.get("solved_status") == "HiddenBad")
        fam_count = Counter(m.get("family") or "Uncertain" for m in members)
        pools.append({
            "src": src,
            "n": len(members),
            "cost_sum": cost_sum,
            "gap_sum": gap_sum,
            "pts_sum": pts_sum,
            "n_solved": n_solved,
            "n_hidden_bad": n_hidden_bad,
            "families": fam_count,
            "members": members,
        })

    # Sort variants
    by_count = sorted(pools, key=lambda p: -p["n"])
    by_cost = sorted(pools, key=lambda p: -p["cost_sum"])
    by_gap = sorted(pools, key=lambda p: -p["gap_sum"])

    lines: list[str] = []
    lines.append("# Cascade-Risk Analysis")
    lines.append("")
    lines.append(f"> Generated by `tools/cascade_report.py` from `task_state.csv` ({len(rows)} task rows). "
                 f"Identifies external sources whose failure would cascade across many tasks, ranked by pool size + LB-points exposure.")
    lines.append("")
    lines.append("## What this is")
    lines.append("")
    lines.append("`current_src` is the source that supplies a task's ONNX payload in the current submission. "
                 "When many tasks share the same external source, a single Kaggle-side issue with that source "
                 "(e.g., a cascade error from one bad ONNX in the pool) takes them all down at once. Conversely, "
                 "writing an organic replacement for a single task in the pool gives a template for the rest.")
    lines.append("")

    # Section 1: Top sources by task count
    lines.append(f"## Top {args.top_sources} cascade pools by task count")
    lines.append("")
    lines.append("| Source | Tasks | Cost sum | Pts sum | Solved | HiddenBad | Top family |")
    lines.append("|---|---:|---:|---:|---:|---:|---|")
    for p in by_count[:args.top_sources]:
        top_fam, top_count = max(p["families"].items(), key=lambda kv: kv[1])
        lines.append(
            f"| `{p['src']}` | {p['n']} | {p['cost_sum']:,.0f} | {p['pts_sum']:,.1f} | "
            f"{p['n_solved']} | {p['n_hidden_bad']} | {top_fam} ({top_count}) |"
        )
    lines.append("")

    # Section 2: Top sources by cost mass
    lines.append(f"## Top {args.top_sources} cascade pools by cost mass (most LB at risk)")
    lines.append("")
    lines.append("| Source | Tasks | Cost sum | Avg cost | Pts at risk¹ |")
    lines.append("|---|---:|---:|---:|---:|")
    for p in by_cost[:args.top_sources]:
        avg_cost = p["cost_sum"] / max(1, p["n"])
        # rough "points at risk" = sum max(1, 25 - log(cost))
        pts_at_risk = sum(max(1.0, 25.0 - math.log(max(1.0, num(m.get("current_cost"))))) for m in p["members"])
        lines.append(f"| `{p['src']}` | {p['n']} | {p['cost_sum']:,.0f} | {avg_cost:,.0f} | {pts_at_risk:,.1f} |")
    lines.append("")
    lines.append("¹ Sum of `max(1, 25 - log(current_cost))` across the pool — approximate LB points contributed by this pool, which would all drop to ~1 if the source cascade-fails.")
    lines.append("")

    # Section 3: Top sources by gap-to-floor (replacement opportunity)
    lines.append(f"## Top {args.top_sources} cascade pools by replacement headroom (largest cost-rewrite opportunity)")
    lines.append("")
    lines.append("| Source | Tasks | Gap to floor sum | Already organic |")
    lines.append("|---|---:|---:|---:|")
    for p in by_gap[:args.top_sources]:
        lines.append(f"| `{p['src']}` | {p['n']} | {p['gap_sum']:,.0f} | {p['n_solved']}/{p['n']} |")
    lines.append("")

    # Section 4: Top tasks within each of the top-3 pools
    lines.append(f"## Top {args.top_tasks_per_source} tasks within each of the largest 5 cascade pools")
    lines.append("")
    lines.append("Within each pool, ranked by `current_cost` descending — these are the individual highest-ROI replacement targets.")
    lines.append("")
    for p in by_count[:5]:
        members = sorted(p["members"], key=lambda m: -num(m.get("current_cost")))
        lines.append(f"### `{p['src']}` ({p['n']} tasks)")
        lines.append("")
        lines.append("| task | cost | points | family | transformations | solved_status |")
        lines.append("|---|---:|---:|---|---|---|")
        for m in members[:args.top_tasks_per_source]:
            t = m.get("task", "")
            cost = m.get("current_cost", "")
            pts = m.get("current_points", "")
            fam = m.get("family", "")
            trans = m.get("transformations", "") or ""
            if len(trans) > 50:
                trans = trans[:47] + "..."
            ss = m.get("solved_status", "")
            lines.append(f"| {t} | {cost} | {pts} | {fam} | {trans} | {ss} |")
        lines.append("")

    # Section 5: Source × family co-occurrence
    lines.append("## Source × family co-occurrence")
    lines.append("")
    lines.append("How tightly is each cascade pool clustered on a single family? "
                 "If a source dominates one family, organic implementations for that family attack the pool's risk efficiently.")
    lines.append("")
    fam_universe = sorted({f for p in pools for f in p["families"]})
    lines.append("| Source | Total | " + " | ".join(fam_universe) + " |")
    lines.append("|---" * (2 + len(fam_universe)) + "|")
    for p in by_count[:args.top_sources]:
        row = [f"`{p['src']}`", str(p["n"])]
        for f in fam_universe:
            n = p["families"].get(f, 0)
            row.append(str(n) if n else "")
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("**Suggested cascade-risk workflow:**")
    lines.append("")
    lines.append("1. Pick the source with the largest pool whose tasks are mostly NotSolved (column `Solved` low vs `Tasks`).")
    lines.append("2. From section 4, pick the 1-3 highest-cost tasks within that pool.")
    lines.append("3. For each: write a numpy verifier → organic ONNX → only submit if the rule is a pure global transform "
                 "(symmetry, periodic-fill, etc.). Anchor-based / template-matching organics tend to hit the silent-fail trap — see `Logs/lessons.md`.")
    lines.append("4. Even if you don't submit, the organic prototype documents an exit path from the cascade-risk pool.")
    lines.append("")

    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote: {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
