"""split_alpha_lanes.py — balanced N-way split of the 400 tasks by scoring headroom.

Scoring headroom proxy: log10(cost + 1). High-cost tasks have more room for cheap
rewrites (max ~25 points per task, current points = max(1, 25 - log(cost))).
Greedy bin-packing assigns each task (sorted descending by headroom) to the lane
with the smallest cumulative headroom so far — produces three roughly-equal
"potential score gain" lanes.

Usage:
    python tools/split_alpha_lanes.py                       # print the split
    python tools/split_alpha_lanes.py --out The_400_Tasks/alpha_sub_lanes.md  # write markdown
    python tools/split_alpha_lanes.py --lane A              # print just Alpha-A's task list
    python tools/split_alpha_lanes.py --worst-first --lane A   # print Alpha-A's queue worst-first

Re-run after updating task_state.csv to refresh the split.
"""

from __future__ import annotations

import argparse
import csv
import math
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TASK_STATE = REPO_ROOT / "The_400_Tasks" / "task_state.csv"

DEFAULT_LANE_COUNT = 2


def _lane_names(n: int) -> list[str]:
    """Generate lane names like Alpha-A, Alpha-B, ... up to n lanes (n <= 26)."""
    if n < 2:
        raise ValueError("need at least 2 lanes")
    if n > 26:
        raise ValueError("more than 26 lanes is silly; cap and re-think")
    return [f"Alpha-{chr(ord('A') + i)}" for i in range(n)]


def _read_tasks() -> list[dict]:
    """Read task_state.csv; coerce cost to float."""
    rows = []
    with TASK_STATE.open(encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                task = int(str(row.get("task_id") or row["task"]).replace("task","") or -1)
            except (KeyError, ValueError):
                continue
            cost_raw = (row.get("cost") or "").strip()
            try:
                cost = float(cost_raw) if cost_raw else 0.0
            except ValueError:
                cost = 0.0
            status = (row.get("best_known_status") or "").strip()
            rows.append({
                "task": task,
                "cost": cost,
                "headroom": math.log10(cost + 1),
                "status": status,
                "source": (row.get("best_known_source") or "").strip(),
            })
    return rows


def _split(rows: list[dict], lane_names: list[str]) -> dict[str, list[dict]]:
    """Snake-draft N-way split: balances BOTH task count and total headroom.

    Sort by headroom descending, then assign in a snake pattern (forward on
    even cycles, reverse on odd). Keeps lane sizes within 1 task of each
    other while distributing high-cost tasks evenly across lanes.
    """
    rows = sorted(rows, key=lambda r: -r["headroom"])
    lanes: dict[str, list[dict]] = {name: [] for name in lane_names}
    n = len(lane_names)
    for i, r in enumerate(rows):
        cycle = i // n
        pos = i % n
        idx = pos if cycle % 2 == 0 else (n - 1 - pos)
        lanes[lane_names[idx]].append(r)
    return lanes


def _format_markdown(lanes: dict[str, list[dict]]) -> str:
    out = []
    out.append("# Alpha sub-lane task assignment\n")
    out.append(f"> Generated by `tools/split_alpha_lanes.py`. **Re-run after material changes to `task_state.csv`** (e.g., after a Kaggle batch lands and task costs shift). The split balances cumulative log-headroom across {len(lanes)} lanes via a snake-draft.\n")
    out.append("")
    out.append("## Ownership rule (read FIRST)\n")
    out.append("**Source of truth:** the lane that owns task NNN is the one whose task-ID list under \"Full task lists per lane\" below contains NNN. Period. No other field, recipe pointer, or `CURRENT_STATE.md` queue line overrides this.\n")
    out.append("**Before claiming any task:**\n")
    out.append("1. Look up the task ID in the per-lane lists below. If it is NOT in your sub-lane's list, **do not touch it** (per `01_MASTER.md` §1.20 lane discipline).")
    out.append("2. Check the OTHER sub-lane's `submissions/_alpha_<x>_scratch/` directory in the main worktree (`${NEUROGOLF_MAIN_ROOT}/submissions/`) for any prototype, builder draft, or `taskNNN_*.py` / `taskNNN_*.onnx` matching your target. **A file there means the other lane is mid-flight on the task — halt and ask the owner before starting.**")
    out.append("3. Recipe-ready handoffs in `CURRENT_STATE.md` and items in `Logs/isolated_probe_recommendations_*.md` are a *pool*, NOT a free-pick — each item still belongs to whichever sub-lane owns its task ID per this file.\n")
    out.append("**If you find yourself wanting to touch a task outside your range** (e.g., \"the recipe is ready and easy, surely it's fine\"), STOP. File an `[A->B]` / `[B->A]` style cross-lane handoff request in `CURRENT_STATE.md` and let the owning lane pick it up. Cross-lane work without explicit owner authorization wastes Kaggle quota when both lanes duplicate the same submission (see `Logs/lessons.md` 2026-05-10 \"Sub-lane task270 collision\").\n")
    out.append("")
    out.append("## Summary\n")
    out.append("| Lane | Task count | Headroom sum (log10 units) | Worst-cost task in lane |")
    out.append("|---|---:|---:|---|")
    for name, tasks in lanes.items():
        if not tasks:
            continue
        head_sum = sum(t["headroom"] for t in tasks)
        worst = max(tasks, key=lambda t: t["cost"])
        out.append(f"| {name} | {len(tasks)} | {head_sum:.2f} | task{worst['task']:03d} (cost {worst['cost']:.0f}) |")
    out.append("")
    out.append("## Worst-scoring first action per lane\n")
    out.append("Each lane's first work item is the task with the highest current cost in the lane (= lowest current points = most headroom for improvement). Per `07_LANES.md`, agents start here and work down the queue until they improve a score OR 1 hour passes.\n")
    for name, tasks in lanes.items():
        worst = sorted(tasks, key=lambda t: -t["cost"])[:5]
        out.append(f"### {name}\n")
        out.append("| Rank | Task | Cost | Headroom | Status | Source |")
        out.append("|---:|---:|---:|---:|---|---|")
        for i, t in enumerate(worst, 1):
            out.append(f"| {i} | task{t['task']:03d} | {t['cost']:.0f} | {t['headroom']:.2f} | {t['status']} | {t['source']} |")
        out.append("")
    out.append("## Full task lists per lane\n")
    for name, tasks in lanes.items():
        ids = sorted(t["task"] for t in tasks)
        # 10 per line for readability
        chunks = [", ".join(f"{i:03d}" for i in ids[k:k+10]) for k in range(0, len(ids), 10)]
        out.append(f"### {name} ({len(ids)} tasks)\n")
        out.append("```")
        out.extend(chunks)
        out.append("```")
        out.append("")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--lanes", type=int, default=DEFAULT_LANE_COUNT, help=f"Number of sub-lanes (default {DEFAULT_LANE_COUNT})")
    parser.add_argument("--out", type=Path, default=None, help="Write markdown to this path")
    parser.add_argument("--lane", default=None, help="Print just one lane, e.g. Alpha-A")
    parser.add_argument("--worst-first", action="store_true", help="With --lane: sort that lane's queue worst-cost first")
    args = parser.parse_args(argv)

    rows = _read_tasks()
    if not rows:
        print("ERROR: no rows read from task_state.csv", file=sys.stderr)
        return 1

    lane_names = _lane_names(args.lanes)
    lanes = _split(rows, lane_names)

    if args.lane:
        if args.lane not in lanes:
            print(f"ERROR: --lane must be one of {lane_names}", file=sys.stderr)
            return 1
        tasks = lanes[args.lane]
        if args.worst_first:
            tasks = sorted(tasks, key=lambda t: -t["cost"])
        else:
            tasks = sorted(tasks, key=lambda t: t["task"])
        for t in tasks:
            print(f"task{t['task']:03d}\tcost={t['cost']:.0f}\theadroom={t['headroom']:.2f}\t{t['status']}\t{t['source']}")
        return 0

    md = _format_markdown(lanes)
    if args.out:
        args.out.write_text(md, encoding="utf-8")
        print(f"wrote {args.out} ({args.out.stat().st_size:,} bytes)")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
