#!/usr/bin/env python3
"""Append a `SPREAD` block to each per-task notes file from a scan JSON.

The block lists every pattern's verdict + cost delta for the task and
suggests next experiments. It lives between the markers
``<!-- SPREAD:BEGIN -->`` and ``<!-- SPREAD:END -->`` so that re-runs
of this tool overwrite the previous block in place without touching
the free-form sections (Rule, Algorithm sketch, Attempts, etc.).

Usage::

    .venv/Scripts/python.exe tools/spread_annotate_notes.py
    .venv/Scripts/python.exe tools/spread_annotate_notes.py --scan Logs/spread_scan_results/spread_scan_YYYYMMDD.json
    .venv/Scripts/python.exe tools/spread_annotate_notes.py --tasks task000,task001
"""
from __future__ import annotations

import argparse
import csv
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
TASK_NOTES_DIR = REPO_ROOT / "The_400_Tasks" / "Task_by_Task"
RESULTS_DIR = REPO_ROOT / "Logs" / "spread_scan_results"

SPREAD_BEGIN = "<!-- SPREAD:BEGIN -->"
SPREAD_END = "<!-- SPREAD:END -->"
BLOCK_RE = re.compile(
    re.escape(SPREAD_BEGIN) + r".*?" + re.escape(SPREAD_END),
    re.DOTALL,
)

VERDICT_GLYPH = {
    "applied": "✓ SAVES",
    "no-op": "—",
    "no-op-after-score": "—",
    "advisory": "?",
    "verify-failed": "✗ verify",
    "regression": "✗ regress",
    "score-failed": "✗ score",
    "skipped": "skip",
    "error": "ERR",
}


def _latest_scan() -> Path | None:
    if not RESULTS_DIR.exists():
        return None
    cands = sorted(RESULTS_DIR.glob("spread_scan_*.json"))
    return cands[-1] if cands else None


def _latest_polish_sweep() -> Path | None:
    if not RESULTS_DIR.exists():
        return None
    cands = sorted(RESULTS_DIR.glob("polish_sweep_*.csv"))
    return cands[-1] if cands else None


def load_polish_sweep(csv_path: Path) -> dict[str, dict[str, Any]]:
    """Load polish-sweep CSV: per-task TRUE sequential-pipeline delta + passes."""
    out: dict[str, dict[str, Any]] = {}
    with csv_path.open(encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            tid = row.get("task_id")
            if not tid:
                continue
            try:
                delta = int(row.get("delta") or 0)
            except ValueError:
                delta = 0
            out[tid] = {
                "delta": delta,
                "applied_passes": [p for p in (row.get("applied_passes") or "").split(",") if p],
                "verify_failed_passes": [p for p in (row.get("verify_failed_passes") or "").split(",") if p],
            }
    return out


def _format_pattern_row(pat: dict[str, Any]) -> str:
    verdict = pat["verdict"]
    glyph = VERDICT_GLYPH.get(verdict, verdict)
    delta = pat.get("cost_delta")
    if delta is None:
        delta_str = "—"
    elif delta > 0:
        delta_str = f"+{delta}"
    else:
        delta_str = str(delta)
    notes = (pat.get("notes") or "").replace("\n", " ").replace("|", "\\|")
    if len(notes) > 80:
        notes = notes[:77] + "..."
    return f"| `{pat['name']}` | {glyph} | {delta_str} | {notes} |"


def _render_spread_block(
    task_record: dict[str, Any],
    scan_date: str,
    polish_info: dict[str, Any] | None = None,
) -> str:
    orig = task_record.get("original") or {}
    patterns = task_record.get("patterns", [])
    has_savings = any(
        p["verdict"] == "applied" and (p.get("cost_delta") or 0) < 0
        for p in patterns
    )
    has_advisory = any(
        p["verdict"] == "advisory" and (p.get("cost_delta") or 0) < 0
        for p in patterns
    )
    lines = [
        SPREAD_BEGIN,
        f"<!-- generated by tools/spread_annotate_notes.py from {scan_date} scan; manual edits OUTSIDE this block -->",
        "",
        f"## Spread-knowledge scan ({scan_date})",
        "",
        f"Current canonical cost: **{orig.get('cost', '?')}**"
        f" (memory={orig.get('memory', '?')}, params={orig.get('params', '?')}, points≈{orig.get('points', '?')}).",
        "",
        "Pattern sweep verdicts (each pattern measured INDEPENDENTLY vs the original — patterns overlap, so the sum overstates the real cumulative savings):",
        "",
        "| Pattern | Verdict | Δ cost (vs original) | Notes |",
        "|---|---|---:|---|",
    ]
    for p in patterns:
        if p["verdict"] in ("no-op", "no-op-after-score") and not (p.get("cost_delta") or 0):
            continue  # audit#2 Phase-1b: 66% of rows were no-op noise; only signal rows emit
        lines.append(_format_pattern_row(p))
    lines.append("")
    # True cumulative savings come from polish_candidate.py's sequential pipeline.
    if polish_info is not None:
        true_delta = polish_info.get("delta", 0)
        applied = polish_info.get("applied_passes", [])
        if true_delta < 0 and applied:
            lines.append(
                f"**Free LB available (sequential pipeline truth)**: running "
                f"`tools/polish_candidate.py` on the current ONNX applies "
                f"{', '.join(f'`{p}`' for p in applied)} and saves **{-true_delta} bytes**"
                f" (byte-exact verified on 3 inputs). Note: the per-pattern Δ above"
                f" was measured against the ORIGINAL, so the per-pattern numbers do not"
                f" sum to this — patterns subsume each other when applied sequentially."
            )
            lines.append("")
        elif true_delta == 0:
            lines.append(
                "**Sequential pipeline result**: 0 bytes saved — already at the floor "
                "for the patterns currently in `tools/spread_patterns/`."
            )
            lines.append("")
    elif has_savings:
        # Fallback when polish-sweep data isn't available.
        savings = sorted(
            [p for p in patterns if p["verdict"] == "applied" and (p.get("cost_delta") or 0) < 0],
            key=lambda p: p["cost_delta"],
        )
        upper_bound = sum(-int(p["cost_delta"]) for p in savings)
        names = ", ".join(f"`{p['name']}` ({p['cost_delta']:+d}b)" for p in savings)
        lines.append(
            f"**Free LB available (UPPER BOUND — patterns overlap)**: applying any of"
            f" {names} reduces cost individually. The UPPER BOUND total is **{upper_bound} bytes** but"
            f" the real cumulative savings (when applying all of them via "
            f"`tools/polish_candidate.py`) is typically lower. Run polish_candidate"
            f" on the current ONNX for the truth."
        )
        lines.append("")
    if has_advisory:
        advs = [p for p in patterns if p["verdict"] == "advisory" and (p.get("cost_delta") or 0) < 0]
        for a in advs:
            est = -int(a.get("cost_delta") or 0)
            lines.append(
                f"**Advisory** ({a['name']}): {a['notes']}"
                f" — estimated savings if applied manually: ~{est} bytes."
            )
        lines.append("")
    regressions = [
        p for p in patterns
        if p["verdict"] in ("regression", "verify-failed") and p.get("cost_delta") is not None
    ]
    if regressions:
        lines.append("**Do NOT apply** (sweep already verified these would hurt):")
        for p in regressions:
            d = p.get("cost_delta")
            d_str = f"+{d}" if d and d > 0 else str(d) if d is not None else "?"
            lines.append(f"- `{p['name']}`: {d_str} bytes ({p['verdict']}). {p['notes']}")
        lines.append("")
    lines.append(
        "_Re-run: `.venv/Scripts/python.exe tools/spread_scan.py` (updates JSON in "
        "`Logs/spread_scan_results/`); then `.venv/Scripts/python.exe tools/spread_annotate_notes.py`."
    )
    lines.append(SPREAD_END)
    return "\n".join(lines)


def _apply_block(notes_path: Path, block: str) -> str:
    """Return new file content with SPREAD block either replaced or appended.
    Returns the original content unchanged if the file does not exist."""
    if not notes_path.exists():
        # Create a minimal stub so the block has somewhere to live.
        return f"# {notes_path.stem}\n\n{block}\n"
    text = notes_path.read_text(encoding="utf-8")
    if SPREAD_BEGIN in text and SPREAD_END in text:
        return BLOCK_RE.sub(block, text)
    # Append at end with a blank-line separator.
    sep = "" if text.endswith("\n\n") else ("\n" if text.endswith("\n") else "\n\n")
    return text + sep + block + "\n"


def annotate(
    scan_json: Path,
    *,
    tasks: list[str] | None = None,
    dry_run: bool = False,
    polish_csv: Path | None = None,
) -> dict[str, int]:
    data = json.loads(scan_json.read_text(encoding="utf-8"))
    scan_date = scan_json.stem.replace("spread_scan_", "")
    counts = {"updated": 0, "skipped_no_record": 0, "created": 0}
    by_task = {t["task_id"]: t for t in data.get("tasks", [])}
    polish_data = load_polish_sweep(polish_csv) if polish_csv and polish_csv.exists() else {}
    task_ids = tasks or sorted(by_task.keys())
    for tid in task_ids:
        rec = by_task.get(tid)
        if rec is None:
            counts["skipped_no_record"] += 1
            continue
        block = _render_spread_block(rec, scan_date, polish_info=polish_data.get(tid))
        notes_path = TASK_NOTES_DIR / f"{tid}.md"
        new_content = _apply_block(notes_path, block)
        existed = notes_path.exists()
        if dry_run:
            counts["updated"] += 1 if existed else 0
            counts["created"] += 0 if existed else 1
            continue
        notes_path.write_text(new_content, encoding="utf-8")
        counts["updated"] += 1 if existed else 0
        counts["created"] += 0 if existed else 1
    return counts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scan", type=Path, default=None, help="Path to spread_scan_*.json (default: latest)")
    parser.add_argument("--polish-csv", type=Path, default=None,
                        help="Path to polish_sweep_*.csv for sequential-pipeline truth (default: latest, optional)")
    parser.add_argument("--tasks", default="", help="Comma-separated taskNNN ids; default = every task in the scan")
    parser.add_argument("--dry-run", action="store_true", help="Don't write files; just report counts")
    args = parser.parse_args(argv)

    scan = args.scan or _latest_scan()
    if scan is None or not scan.exists():
        print(f"No scan JSON found in {RESULTS_DIR}; run tools/spread_scan.py first.")
        return 2

    polish_csv = args.polish_csv if args.polish_csv else _latest_polish_sweep()
    tasks = [t.strip() for t in args.tasks.split(",") if t.strip()] or None
    counts = annotate(scan, tasks=tasks, dry_run=args.dry_run, polish_csv=polish_csv)
    print(f"Scan: {scan}")
    if polish_csv and polish_csv.exists():
        print(f"Polish sweep: {polish_csv}")
    print(f"Updated: {counts['updated']}  Created: {counts['created']}  Skipped: {counts['skipped_no_record']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
