#!/usr/bin/env python3
"""context_pack.py — one command, one curated per-task context pack (~10-14 KB).

Replaces a worker's 4-6 task-specific file reads: task_state row, current cost,
taskNNN.md STATUS + prioritized manual sections (Rule / Don't-do / Floor /
Attempts), the active prompt, staged candidates, prototype inventory, and the
library §-anchors cited by all of the above. Whale-safe: hard byte budget with
explicit truncation pointers — it will never dump a 200 KB journal at you.

Usage:
    python tools/agent_helpers/context_pack.py --task 205
    python tools/agent_helpers/context_pack.py --task 233 --max-kb 10
    python tools/agent_helpers/context_pack.py --task 205 --out pack205.md
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]

MARKER_RE = re.compile(
    r"<!--\s*(AUTO|HIST|GDIAG|SPREAD):BEGIN\s*-->.*?<!--\s*\1:END\s*-->",
    re.DOTALL,
)
ANCHOR_RE = re.compile(r"(§[A-Za-z0-9][\w-]*|#\d{2}\b)")

# heading keywords -> priority (lower = include first)
SECTION_PRIORITY = [
    (0, ("rule",)),
    (1, ("don't", "dont", "do not", "avoid", "trap")),
    (2, ("floor",)),
    (3, ("current best", "best", "shipped", "compressed history")),
    (4, ("attempt", "lineage", "version")),
    (5, ("cost",)),
    (6, ("open", "next", "idea", "todo")),
]


def _read(p: Path) -> str:
    return p.read_text(encoding="utf-8", errors="replace")


def section_priority(heading: str) -> int:
    low = heading.lower()
    for prio, keys in SECTION_PRIORITY:
        if any(k in low for k in keys):
            return prio
    return 9


def task_state_row(n: int) -> dict:
    csv_p = REPO / "The_400_Tasks" / "task_state.csv"
    with csv_p.open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["task"] == f"task{n:03d}":
                return row
    return {}


def split_sections(manual_text: str) -> list[tuple[str, str]]:
    """[(heading, body)] split on ## headings; pre-heading text gets heading ''. """
    parts = re.split(r"^(##+ .*)$", manual_text, flags=re.M)
    out: list[tuple[str, str]] = []
    if parts[0].strip():
        out.append(("", parts[0]))
    for i in range(1, len(parts) - 1, 2):
        out.append((parts[i].strip(), parts[i + 1]))
    return out


def cap(text: str, limit: int, pointer: str) -> str:
    b = text.encode("utf-8")
    if len(b) <= limit:
        return text
    cut = b[:limit].decode("utf-8", errors="ignore")
    return cut + f"\n> [...truncated — full text in {pointer}]\n"


def build_pack(n: int, max_kb: float) -> str:
    budget = int(max_kb * 1024)
    n3 = f"{n:03d}"
    out: list[str] = []

    # --- header from task_state ---
    row = task_state_row(n)
    out.append(f"# context pack — task{n3}  (generated by context_pack.py; do not edit)")
    if row:
        out.append("")
        out.append(f"- family: **{row.get('family','?')}** | transformations: {row.get('transformations','?')} "
                   f"| complexity: {row.get('complexity_1_10','?')}")
        out.append(f"- current cost: **{row.get('current_cost','?')}** (points {float(row.get('current_points') or 0):.2f})"
                   + " | source: task_state.csv")
        out.append(f"- team_split: **{row.get('team_split','?')}** | hidden_bad_history: {row.get('hidden_bad_history','?')} "
                   f"| structural_attempt: {row.get('structural_attempt','?')}")
        if row.get("similar_tasks"):
            sims = row["similar_tasks"].split(",")
            shown = ",".join(sims[:8]) + (f" (+{len(sims)-8} more)" if len(sims) > 8 else "")
            out.append(f"- similar tasks: {shown}")
        if (row.get("notes") or "").strip():
            out.append(f"- state notes: {row['notes'][:300]}")

    md_path = REPO / "The_400_Tasks" / "Task_by_Task" / f"task{n3}.md"
    manual = ""
    if md_path.exists():
        full = _read(md_path)
        m = re.search(r"^\*\*STATUS:\*\*.*$", full, re.M)
        if m:
            out.append(f"\n## STATUS\n{m.group(0)}")
        manual = MARKER_RE.sub("", full)

    # --- active prompt ---
    for folder in ("1", "2"):
        hits = sorted((REPO / "The_400_Tasks" / "Task Prompts" / folder).glob(f"*Task{n3}_*.md"))
        if hits:
            head = "\n".join(_read(hits[0]).splitlines()[:14])
            out.append(f"\n## ACTIVE PROMPT ({hits[0].name})\n{cap(head, 1600, hits[0].name)}")
            break

    # --- staged candidates ---
    staged_root = REPO / "The_400_Tasks" / "Task_by_Task" / f"task{n3}" / "staged_candidates"
    staged = sorted(
        p for p in staged_root.glob(f"task{n3}_*")
        if p.is_dir()
    ) if staged_root.exists() else []
    if staged:
        out.append("\n## STAGED CANDIDATES (task-local staged_candidates/)")
        for d in staged[-8:]:
            cost = ""
            mf = d / "manifest.json"
            if mf.exists():
                try:
                    j = json.loads(_read(mf))
                    cost = f" — cost {j.get('cost', '?')}"
                except Exception:
                    pass
            out.append(f"- {d.name}{cost}")

    # --- prototypes inventory ---
    proto = REPO / "The_400_Tasks" / "Task_by_Task" / f"task{n3}" / "prototypes"
    if proto.exists():
        files = sorted(proto.iterdir(), key=lambda p: p.stat().st_mtime, reverse=True)
        by_ext: dict[str, int] = {}
        for f in files:
            by_ext[f.suffix] = by_ext.get(f.suffix, 0) + 1
        summary = ", ".join(f"{v}×{k or '(none)'}" for k, v in sorted(by_ext.items(), key=lambda x: -x[1]))
        newest = ", ".join(f.name for f in files[:5])
        out.append(f"\n## PROTOTYPES ({len(files)} files: {summary})\nnewest: {newest}")

    # --- prioritized manual sections within remaining budget ---
    if manual:
        spent = len("\n".join(out).encode("utf-8"))
        remaining = max(2048, budget - spent - 1024)  # reserve 1 KB for footer/anchors
        sections = sorted(split_sections(manual), key=lambda s: section_priority(s[0]))
        included, skipped = [], []
        per_section_cap = max(1500, remaining // 5)
        for heading, body in sections:
            block = (heading + "\n" if heading else "") + body.strip() + "\n"
            block = cap(block, per_section_cap, f"Task_by_Task/task{n3}.md")
            blen = len(block.encode("utf-8"))
            if blen <= remaining:
                included.append(block)
                remaining -= blen
            else:
                skipped.append(heading or "(intro)")
        if included:
            out.append(f"\n## TASK NOTES (prioritized from task{n3}.md — Rule > Don't-do > Floor > Attempts)")
            out.extend(included)
        if skipped:
            out.append(f"\n> sections not packed (read the file if needed): {', '.join(skipped[:12])}")

    # --- cited library anchors ---
    anchors = sorted(set(ANCHOR_RE.findall("\n".join(out))))
    if anchors:
        out.append(f"\n## CITED LIBRARY ANCHORS\ngrep these in Onnx_Advanced/techniques.md + traps.md: {', '.join(anchors)}")

    out.append(f"\n---\nfull sources: Task_by_Task/task{n3}.md · show_task.py --task {n} · "
               f"WORKER_PROTOCOL.md (the contract) · prompt file above")
    return "\n".join(out) + "\n"


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--task", required=True, type=int)
    ap.add_argument("--max-kb", type=float, default=14.0)
    ap.add_argument("--out", help="write to file instead of stdout")
    args = ap.parse_args()

    pack = build_pack(args.task, args.max_kb)
    if args.out:
        Path(args.out).write_text(pack, encoding="utf-8")
        print(f"wrote {args.out} ({len(pack.encode('utf-8'))/1024:.1f} KB)")
    else:
        print(pack)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
